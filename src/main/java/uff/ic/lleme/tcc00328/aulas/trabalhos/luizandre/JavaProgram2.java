package uff.ic.lleme.tcc00328.aulas.trabalhos.luizandre;

public class JavaProgram2 {

    // function
    public static int fatorial(int n) {
        int fatorial = 1; // local variable
        for (int i = fatorial; i <= n; i++)
            fatorial = fatorial * i;
        return fatorial;
    }
}
